# =============================================================================
# Configure SSL Certificates
# =============================================================================
setup_ssl_certificates() {
    log_info "Setting up SSL certificates..."
    
    local ssl_dir="$DEPLOY_DIR/nginx/ssl"
    mkdir -p "$ssl_dir"
    
    # Check if Let's Encrypt certificates should be used
    if [ "${USE_LETS_ENCRYPT:-true}" = "true" ]; then
        log_info "Configuring Let's Encrypt certificates..."
        
        # Create certbot directory for ACME challenges
        mkdir -p "$DEPLOY_DIR/certbot/www"
        
        # Check if certbot is available
        if command -v certbot &> /dev/null; then
            # Request certificate (requires DNS to be configured first)
            local domains=("portal.algeriatrade.dz" "api.algeriatrade.dz")
            
            for domain in "${domains[@]}"; do
                certbot certonly \
                    --webroot \
                    -w "$DEPLOY_DIR/certbot/www" \
                    -d "$domain" \
                    --non-interactive \
                    --agree-tos \
                    --email "admin@algeriatrade.dz" || \
                    log_warn "Could not obtain certificate for $domain. Using self-signed."
            done
            
            # Copy certificates to nginx ssl directory
            if [ -f "/etc/letsencrypt/live/portal.algeriatrade.dz/fullchain.pem" ]; then
                cp /etc/letsencrypt/live/portal.algeriatrade.dz/fullchain.pem "$ssl_dir/"
                cp /etc/letsencrypt/live/portal.algeriatrade.dz/privkey.pem "$ssl_dir/"
                cp /etc/letsencrypt/live/portal.algeriatrade.dz/chain.pem "$ssl_dir/"
                log_success "Let's Encrypt certificates installed."
            fi
        else
            log_warn "Certbot not found. Generating self-signed certificates..."
            generate_self_signed_certs
        fi
    else
        generate_self_signed_certs
    fi
}

generate_self_signed_certs() {
    local ssl_dir="$DEPLOY_DIR/nginx/ssl"
    
    # Generate self-signed certificate for development/testing
    openssl req -x509 -nodes -days 365 -newkey rsa:2048 \
        -keyout "$ssl_dir/privkey.pem" \
        -out "$ssl_dir/fullchain.pem" \
        -subj "/C=DZ/O=AlgeriaTrade.dz/CN=*.algeriatrade.dz" \
        -addext "subjectAltName=DNS:*.algeriatrade.dz,DNS:localhost"
    
    # Create chain file (same as fullchain for self-signed)
    cp "$ssl_dir/fullchain.pem" "$ssl_dir/chain.pem"
    
    log_warn "Self-signed certificates generated. Use only for testing!"
}

# =============================================================================
# Configure Email Service
# =============================================================================
configure_email_service() {
    log_info "Configuring email service..."
    
    local env_file="$DEPLOY_DIR/.env.production"
    
    # Prompt for SMTP configuration if not already set
    if ! grep -q "SMTP_HOST=" "$env_file" 2>/dev/null; then
        echo ""
        log_info "Please enter your SMTP configuration:"
        
        read -rp "SMTP Host [smtp.mailgun.org]: " smtp_host
        smtp_host="${smtp_host:-smtp.mailgun.org}"
        
        read -rp "SMTP Port [587]: " smtp_port
        smtp_port="${smtp_port:-587}"
        
        read -rp "SMTP User [postmaster@algeriatrade.dz]: " smtp_user
        smtp_user="${smtp_user:-postmaster@algeriatrade.dz}"
        
        read -rsp "SMTP Password: " smtp_pass
        echo ""
        
        cat >> "$env_file" << EOF
SMTP_HOST=${smtp_host}
SMTP_PORT=${smtp_port}
SMTP_USER=${smtp_user}
SMTP_PASS=${smtp_pass}
EMAIL_FROM=noreply@algeriatrade.dz
EOF
        
        log_success "Email configuration saved."
    fi
    
    # Test email connection
    if command -v python3 &> /dev/null; then
        log_info "Testing SMTP connection..."
        source "$env_file"
        python3 << PYTEST
import smtplib
try:
    server = smtplib.SMTP("${SMTP_HOST}", ${SMTP_PORT})
    server.starttls()
    server.login("${SMTP_USER}", "${SMTP_PASS}")
    server.quit()
    print("Email connection test successful!")
except Exception as e:
    print(f"Email test failed: {e}")
PYTEST
    fi
}

