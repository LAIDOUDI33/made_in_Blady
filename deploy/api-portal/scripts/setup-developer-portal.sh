# =============================================================================
# Generate Secure Secrets
# =============================================================================
generate_secrets() {
    log_info "Generating secure secrets..."
    
    local env_file="$DEPLOY_DIR/.env.production"
    
    # Create .env file if it doesn't exist
    if [ ! -f "$env_file" ]; then
        cat > "$env_file" << 'EOF'
# AlgeriaTrade.dz API Developer Portal - Production Environment
# Generated by setup script on $(date)
EOF
    fi
    
    # Generate JWT Secret (256 bits = 32 bytes)
    if ! grep -q "JWT_SECRET=" "$env_file" 2>/dev/null; then
        local jwt_secret=$(openssl rand -base64 32 | tr -d '\n')
        echo "JWT_SECRET=${jwt_secret}" >> "$env_file"
        log_success "Generated JWT_SECRET"
    fi
    
    # Generate JWT Refresh Secret (different from access token secret)
    if ! grep -q "JWT_REFRESH_SECRET=" "$env_file" 2>/dev/null; then
        local refresh_secret=$(openssl rand -base64 32 | tr -d '\n')
        echo "JWT_REFRESH_SECRET=${refresh_secret}" >> "$env_file"
        log_success "Generated JWT_REFRESH_SECRET"
    fi
    
    # Generate Encryption Key (AES-256-GCM requires 256-bit key)
    if ! grep -q "ENCRYPTION_KEY=" "$env_file" 2>/dev/null; then
        local enc_key=$(openssl rand -hex 32)
        echo "ENCRYPTION_KEY=${enc_key}" >> "$env_file"
        log_success "Generated ENCRYPTION_KEY"
    fi
    
    # Generate Webhook Secret
    if ! grep -q "WEBHOOK_SECRET=" "$env_file" 2>/dev/null; then
        local webhook_secret=$(openssl rand -hex 24)
        echo "WEBHOOK_SECRET=${webhook_secret}" >> "$env_file"
        log_success "Generated WEBHOOK_SECRET"
    fi
    
    # Generate PostgreSQL Password
    if ! grep -q "POSTGRES_PASSWORD=" "$env_file" 2>/dev/null; then
        local pg_password=$(openssl rand -base64 16 | tr -d '=' | cut -c1-20)
        echo "POSTGRES_PASSWORD=${pg_password}" >> "$env_file"
        log_success "Generated POSTGRES_PASSWORD"
    fi
    
    # Generate Redis Password
    if ! grep -q "REDIS_PASSWORD=" "$env_file" 2>/dev/null; then
        local redis_password=$(openssl rand -base64 16 | tr -d '=' | cut -c1-20)
        echo "REDIS_PASSWORD=${redis_password}" >> "$env_file"
        log_success "Generated REDIS_PASSWORD"
    fi
    
    # Generate Admin Password
    if ! grep -q "ADMIN_INITIAL_PASSWORD=" "$env_file" 2>/dev/null; then
        local admin_pass=$(openssl rand -base64 12 | tr -d '=' | cut -c1-16)
        echo "ADMIN_INITIAL_PASSWORD=${admin_pass}" >> "$env_file"
        log_success "Generated ADMIN_INITIAL_PASSWORD: ${admin_pass}"
        log_warn "Save this admin password securely!"
    fi
    
    log_success "Secrets generation completed."
}

# =============================================================================
# Create Database Schema
# =============================================================================
create_database_schema() {
    log_info "Creating database schema..."
    
    cd "$PROJECT_ROOT"
    
    # Ensure Prisma is installed
    if [ ! -d "node_modules/@prisma/client" ]; then
        npm install @prisma/client prisma --save-dev
    fi
    
    # Generate Prisma client
    npx prisma generate
    
    # Create initial migration
    npx prisma migrate dev --name init --create-only || true
    
    # Push schema to database (for production, use migrate deploy)
    npx prisma db push || {
        log_error "Failed to create database schema!"
        exit 1
    }
    
    log_success "Database schema created."
}

